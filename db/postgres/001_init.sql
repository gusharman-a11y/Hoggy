-- Hoggy: Postgres schema (Supabase project, schema `hoggy`).
-- Idempotent: runs on a fresh database and can be run again at any time. The server runs this same file on a cold start
-- whenever its hash differs from the one recorded in hoggy.meta (key 'schema_hash'), under an advisory lock.
-- Times are milliseconds since the epoch (BIGINT). Files (receipts, proof uploads) are BYTEA, size-capped; Supabase Storage
-- is the better long-term home for them.
-- Security: the server connects as `postgres` (table owner, bypasses RLS). Every table has RLS ON and NO policies, and
-- anon/authenticated have no grants, so the public Data API sees nothing.

CREATE SCHEMA IF NOT EXISTS hoggy;

CREATE TABLE IF NOT EXISTS hoggy.users(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  name TEXT,
  pass TEXT NOT NULL,
  inbox TEXT UNIQUE NOT NULL,
  created BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS hoggy.sessions(
  sid TEXT PRIMARY KEY,                 -- sha256 of the cookie value
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  expires BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_user ON hoggy.sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_expires ON hoggy.sessions(expires);

CREATE TABLE IF NOT EXISTS hoggy.state(
  user_id BIGINT PRIMARY KEY REFERENCES hoggy.users(id) ON DELETE CASCADE,
  json TEXT NOT NULL,
  rev INTEGER NOT NULL DEFAULT 0,
  updated BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS hoggy.inbox(
  id TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  vendor TEXT, amount DOUBLE PRECISION, currency TEXT, date TEXT, category TEXT, subject TEXT, sender TEXT,
  file_id TEXT, file_name TEXT, file_type TEXT,
  created BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS inbox_user ON hoggy.inbox(user_id);
CREATE INDEX IF NOT EXISTS inbox_created ON hoggy.inbox(created);

CREATE TABLE IF NOT EXISTS hoggy.conferences(
  id TEXT PRIMARY KEY,
  json TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'published',
  source TEXT,
  updated BIGINT NOT NULL,
  checked BIGINT NOT NULL DEFAULT 0,
  seedhash TEXT);
CREATE INDEX IF NOT EXISTS conferences_status ON hoggy.conferences(status);

CREATE TABLE IF NOT EXISTS hoggy.candidates(
  id TEXT PRIMARY KEY,
  source TEXT,
  json TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  created BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS hoggy.ingest_runs(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started BIGINT, finished BIGINT, summary TEXT);

-- receipt files: emailed attachments and each user's server copy of their receipts (16 MB cap, 100 MB per user in code)
CREATE TABLE IF NOT EXISTS hoggy.files(
  id TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  name TEXT, type TEXT,
  data BYTEA NOT NULL CONSTRAINT files_size CHECK (octet_length(data) <= 16000000));
CREATE INDEX IF NOT EXISTS files_user ON hoggy.files(user_id);

CREATE TABLE IF NOT EXISTS hoggy.date_changes(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conf_id TEXT NOT NULL,
  patch TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  created BIGINT NOT NULL,
  UNIQUE(conf_id, patch));

-- reviews: one per user per conference series per edition year
CREATE TABLE IF NOT EXISTS hoggy.reviews(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  series_key TEXT NOT NULL,
  edition_year INTEGER NOT NULL,
  conf_id TEXT, city TEXT,
  rating DOUBLE PRECISION NOT NULL,
  content INTEGER, networking INTEGER, venue INTEGER, value INTEGER, cpd INTEGER,
  text TEXT NOT NULL, author TEXT NOT NULL,
  created BIGINT NOT NULL, updated BIGINT NOT NULL,
  verify TEXT NOT NULL DEFAULT 'none',
  verified_by TEXT,
  UNIQUE(user_id, series_key, edition_year));
CREATE INDEX IF NOT EXISTS rv2_series ON hoggy.reviews(series_key);

CREATE TABLE IF NOT EXISTS hoggy.review_reports(
  review_id BIGINT NOT NULL REFERENCES hoggy.reviews(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  created BIGINT NOT NULL,
  weight INTEGER DEFAULT 1,
  PRIMARY KEY(review_id, user_id));

-- proof of attendance uploads: private, admin-only, the file (data) is set to NULL once an admin decides (5 MB cap)
CREATE TABLE IF NOT EXISTS hoggy.review_proofs(
  id TEXT PRIMARY KEY,
  review_id BIGINT NOT NULL REFERENCES hoggy.reviews(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL, name TEXT, type TEXT NOT NULL, size INTEGER NOT NULL,
  data BYTEA CONSTRAINT review_proofs_size CHECK (data IS NULL OR octet_length(data) <= 5000000),
  status TEXT NOT NULL DEFAULT 'pending', note TEXT,
  created BIGINT NOT NULL, decided BIGINT, decided_by TEXT);
CREATE INDEX IF NOT EXISTS rp_review ON hoggy.review_proofs(review_id);

-- registration receipts received by email that verify attendance of an edition
CREATE TABLE IF NOT EXISTS hoggy.attend_receipts(
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  series_key TEXT NOT NULL, edition_year INTEGER NOT NULL,
  conf_id TEXT NOT NULL, inbox_id TEXT, receipt_date TEXT,
  created BIGINT NOT NULL,
  PRIMARY KEY(user_id, series_key, edition_year));

-- server settings shared by every instance: schema_hash, conf_seed_hash, inbound_secret (when HOGGY_INBOUND_SECRET is unset)
CREATE TABLE IF NOT EXISTS hoggy.meta(
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL);

-- rate limits shared by every serverless instance (key is a sha256 prefix, never an email or IP)
CREATE TABLE IF NOT EXISTS hoggy.rate_hits(
  key TEXT NOT NULL,
  t BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS rate_hits_key_t ON hoggy.rate_hits(key, t);
CREATE INDEX IF NOT EXISTS rate_hits_t ON hoggy.rate_hits(t);

-- Row level security ON for every table in the schema, with no policies: only the owner / BYPASSRLS roles read anything.
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'hoggy' LOOP
    EXECUTE format('ALTER TABLE hoggy.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

-- No access for the public API roles (Supabase anon / authenticated), nor for PUBLIC.
REVOKE ALL ON SCHEMA hoggy FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA hoggy FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA hoggy FROM PUBLIC;
DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA hoggy FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA hoggy FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA hoggy FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA hoggy FROM %I', r);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA hoggy REVOKE ALL ON TABLES FROM %I', r);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA hoggy REVOKE ALL ON SEQUENCES FROM %I', r);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA hoggy REVOKE ALL ON FUNCTIONS FROM %I', r);
    END IF;
  END LOOP;
END $$;

-- The server's role keeps full access even if another role (e.g. a migration tool) created the tables.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'postgres') THEN
    GRANT USAGE ON SCHEMA hoggy TO postgres;
    GRANT ALL ON ALL TABLES IN SCHEMA hoggy TO postgres;
    GRANT ALL ON ALL SEQUENCES IN SCHEMA hoggy TO postgres;
  END IF;
END $$;
