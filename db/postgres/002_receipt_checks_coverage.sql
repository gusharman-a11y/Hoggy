-- Hoggy: Postgres schema, step 2 (after 001_init.sql). Schema `hoggy`.
-- Idempotent. The server runs it on a cold start whenever its hash differs from hoggy.meta key 'schema_hash:002', under the
-- same advisory lock as 001. Apply it by hand in the Supabase SQL editor first if you like; running it twice is harmless.
--   receipt_checks: a registration receipt emailed to a user's Hoggy address that matched a conference edition. It no longer
--                   verifies a review on its own (owner's decision B): an admin approves or rejects it at /admin.html.
--                   The copy of the receipt file (data) is set to NULL once an admin decides.
--   coverage:       "Covered in" links (journal and press coverage) per conference series. Links only, no article text.
-- Security as in 001: RLS ON with no policies; nothing for PUBLIC, anon or authenticated.

CREATE TABLE IF NOT EXISTS hoggy.receipt_checks(
  id TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  series_key TEXT NOT NULL,
  edition_year INTEGER NOT NULL,
  conf_id TEXT NOT NULL,
  inbox_id TEXT,
  vendor TEXT, amount DOUBLE PRECISION, currency TEXT, receipt_date TEXT, subject TEXT,
  file_name TEXT, file_type TEXT, size INTEGER NOT NULL DEFAULT 0,
  data BYTEA CONSTRAINT receipt_checks_size CHECK (data IS NULL OR octet_length(data) <= 16000000),
  status TEXT NOT NULL DEFAULT 'pending',
  note TEXT,
  created BIGINT NOT NULL, decided BIGINT, decided_by TEXT);
CREATE INDEX IF NOT EXISTS rc_edition ON hoggy.receipt_checks(user_id, series_key, edition_year);
CREATE INDEX IF NOT EXISTS rc_status ON hoggy.receipt_checks(status);

CREATE TABLE IF NOT EXISTS hoggy.coverage(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  series_key TEXT NOT NULL,
  type TEXT NOT NULL CONSTRAINT coverage_type CHECK (type IN ('meeting-report', 'abstract-supplement', 'society-journal', 'news')),
  title TEXT,
  publication TEXT NOT NULL CONSTRAINT coverage_publication CHECK (length(btrim(publication)) > 0),
  year INTEGER,
  url TEXT NOT NULL CONSTRAINT coverage_https CHECK (url LIKE 'https://%'),
  added_by BIGINT REFERENCES hoggy.users(id) ON DELETE SET NULL,
  added_on BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  decided BIGINT, decided_by TEXT,
  UNIQUE(series_key, url));
CREATE INDEX IF NOT EXISTS coverage_series ON hoggy.coverage(series_key, status);

ALTER TABLE hoggy.receipt_checks ENABLE ROW LEVEL SECURITY;
ALTER TABLE hoggy.coverage ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON hoggy.receipt_checks, hoggy.coverage FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA hoggy FROM PUBLIC;
DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON hoggy.receipt_checks, hoggy.coverage FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA hoggy FROM %I', r);
    END IF;
  END LOOP;
END $$;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'postgres') THEN
    GRANT ALL ON hoggy.receipt_checks, hoggy.coverage TO postgres;
    GRANT ALL ON ALL SEQUENCES IN SCHEMA hoggy TO postgres;
  END IF;
END $$;
