-- Hoggy: Postgres schema, step 3 (after 002). Schema `hoggy`. Hospitals (organisations), roles, trip approval, study
-- budgets, claims to finance and in-app notifications. All optional: a doctor without a hospital never gets a row here.
-- Idempotent. The server runs it on a cold start whenever its hash differs from hoggy.meta key 'schema_hash:003', under the
-- same advisory lock as 001 and 002. Running it twice is harmless.
--   orgs:          a hospital. join_code is 8 characters (no 0/O/1/I), stored without the dash; claims_email is where the
--                  claim pack goes by default; default_allowance_cents is the yearly study allowance for each member.
--   memberships:   one hospital per user (user_id is the primary key). role doctor | manager | finance | admin.
--   allowances:    a manager's per-person, per-year override of the hospital default.
--   approvals:     a doctor's request to attend an event. Server-side record: the client's synced trip state is never trusted
--                  for its status. trip_ref is the id of the trip in the doctor's synced state; snapshot is the event (name,
--                  city, dates) and the cost breakdown at the time of the request. Nobody decides their own request.
--   claims:        a claim the doctor marked as submitted to finance, with the claim-pack total; finance marks it paid.
--   notifications: in-app notices (no email until decision D3).
-- Security as in 001: RLS ON with no policies; nothing for PUBLIC, anon or authenticated. Every query in server.js filters
-- by the caller's membership.

CREATE TABLE IF NOT EXISTS hoggy.orgs(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CONSTRAINT orgs_name CHECK (length(btrim(name)) > 0),
  join_code TEXT NOT NULL UNIQUE CONSTRAINT orgs_code CHECK (join_code ~ '^[A-HJ-NP-Z2-9]{8}$'),
  claims_email TEXT,
  default_allowance_cents BIGINT NOT NULL DEFAULT 0 CONSTRAINT orgs_allowance CHECK (default_allowance_cents >= 0),
  currency TEXT NOT NULL DEFAULT 'AUD',
  created BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS hoggy.memberships(
  user_id BIGINT PRIMARY KEY REFERENCES hoggy.users(id) ON DELETE CASCADE,
  org_id BIGINT NOT NULL REFERENCES hoggy.orgs(id) ON DELETE CASCADE,
  role TEXT NOT NULL CONSTRAINT memberships_role CHECK (role IN ('doctor', 'manager', 'finance', 'admin')),
  created BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS memberships_org ON hoggy.memberships(org_id, role);

CREATE TABLE IF NOT EXISTS hoggy.allowances(
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  org_id BIGINT NOT NULL REFERENCES hoggy.orgs(id) ON DELETE CASCADE,
  year INTEGER NOT NULL,
  allowance_cents BIGINT NOT NULL CONSTRAINT allowances_cents CHECK (allowance_cents >= 0),
  set_by BIGINT REFERENCES hoggy.users(id) ON DELETE SET NULL,
  updated BIGINT NOT NULL,
  PRIMARY KEY(user_id, org_id, year));

CREATE TABLE IF NOT EXISTS hoggy.approvals(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id BIGINT NOT NULL REFERENCES hoggy.orgs(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  trip_ref TEXT NOT NULL,
  conf_id TEXT,
  snapshot TEXT NOT NULL,
  year INTEGER NOT NULL,
  estimate_cents BIGINT NOT NULL CONSTRAINT approvals_estimate CHECK (estimate_cents > 0),
  currency TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CONSTRAINT approvals_status CHECK (status IN ('pending', 'approved', 'rejected')),
  manager_comment TEXT,
  decided_by BIGINT REFERENCES hoggy.users(id) ON DELETE SET NULL,
  created BIGINT NOT NULL, updated BIGINT NOT NULL, decided BIGINT,
  UNIQUE(org_id, user_id, trip_ref));
CREATE INDEX IF NOT EXISTS approvals_org_status ON hoggy.approvals(org_id, status);
CREATE INDEX IF NOT EXISTS approvals_user ON hoggy.approvals(user_id, year);

CREATE TABLE IF NOT EXISTS hoggy.claims(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id BIGINT NOT NULL REFERENCES hoggy.orgs(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  approval_id BIGINT REFERENCES hoggy.approvals(id) ON DELETE SET NULL,
  trip_ref TEXT NOT NULL,
  conf_id TEXT,
  snapshot TEXT NOT NULL,
  year INTEGER NOT NULL,
  total_cents BIGINT NOT NULL CONSTRAINT claims_total CHECK (total_cents > 0),
  currency TEXT NOT NULL,
  receipts INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'submitted' CONSTRAINT claims_status CHECK (status IN ('submitted', 'paid')),
  submitted BIGINT NOT NULL, paid BIGINT,
  paid_by BIGINT REFERENCES hoggy.users(id) ON DELETE SET NULL,
  UNIQUE(org_id, user_id, trip_ref));
CREATE INDEX IF NOT EXISTS claims_org_status ON hoggy.claims(org_id, status);
CREATE INDEX IF NOT EXISTS claims_user ON hoggy.claims(user_id, year);

CREATE TABLE IF NOT EXISTS hoggy.notifications(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES hoggy.users(id) ON DELETE CASCADE,
  org_id BIGINT REFERENCES hoggy.orgs(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  text TEXT NOT NULL,
  link TEXT,
  created BIGINT NOT NULL,
  seen BIGINT);
CREATE INDEX IF NOT EXISTS notifications_user ON hoggy.notifications(user_id, created);

ALTER TABLE hoggy.orgs ENABLE ROW LEVEL SECURITY;
ALTER TABLE hoggy.memberships ENABLE ROW LEVEL SECURITY;
ALTER TABLE hoggy.allowances ENABLE ROW LEVEL SECURITY;
ALTER TABLE hoggy.approvals ENABLE ROW LEVEL SECURITY;
ALTER TABLE hoggy.claims ENABLE ROW LEVEL SECURITY;
ALTER TABLE hoggy.notifications ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON hoggy.orgs, hoggy.memberships, hoggy.allowances, hoggy.approvals, hoggy.claims, hoggy.notifications FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA hoggy FROM PUBLIC;
DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON hoggy.orgs, hoggy.memberships, hoggy.allowances, hoggy.approvals, hoggy.claims, hoggy.notifications FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA hoggy FROM %I', r);
    END IF;
  END LOOP;
END $$;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'postgres') THEN
    GRANT ALL ON hoggy.orgs, hoggy.memberships, hoggy.allowances, hoggy.approvals, hoggy.claims, hoggy.notifications TO postgres;
    GRANT ALL ON ALL SEQUENCES IN SCHEMA hoggy TO postgres;
  END IF;
END $$;
