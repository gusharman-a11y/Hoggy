-- Hoggy: Postgres schema, step 4 (after 003). Schema `hoggy`. Organiser listings and listing problem reports.
-- Idempotent. The server runs it on a cold start whenever its hash differs from hoggy.meta key 'schema_hash:004', under the
-- same advisory lock as 001 to 003. Running it twice is harmless.
--   submissions:     "List your event": an organiser's conference or course session, waiting for an admin. json holds the
--                    public fields; contact_email is kept here only (never served publicly, never copied into the listing).
--                    On approval the listing becomes a row in hoggy.conferences with source 'organiser-submitted' (the seed
--                    from data/conferences.js never overwrites that source, so it survives every data merge) and conf_id
--                    points at it. ip_hash is a truncated SHA-256 of the sender's network address, for abuse checks only.
--   listing_reports: "Report a problem with this listing" on a conference or course page, for the admin desk.
-- Security as in 001: RLS ON with no policies; nothing for PUBLIC, anon or authenticated.

CREATE TABLE IF NOT EXISTS hoggy.submissions(
  id TEXT PRIMARY KEY,
  json TEXT NOT NULL,
  contact_email TEXT NOT NULL CONSTRAINT submissions_email CHECK (length(contact_email) BETWEEN 3 AND 254),
  user_id BIGINT REFERENCES hoggy.users(id) ON DELETE SET NULL,
  ip_hash TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CONSTRAINT submissions_status CHECK (status IN ('pending', 'approved', 'rejected')),
  conf_id TEXT,
  note TEXT,
  created BIGINT NOT NULL, decided BIGINT, decided_by TEXT);
CREATE INDEX IF NOT EXISTS submissions_status_created ON hoggy.submissions(status, created);

CREATE TABLE IF NOT EXISTS hoggy.listing_reports(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CONSTRAINT listing_reports_kind CHECK (kind IN ('conference', 'course')),
  ref_id TEXT NOT NULL,
  reason TEXT NOT NULL CONSTRAINT listing_reports_reason CHECK (reason IN ('wrong-date', 'wrong-city', 'duplicate', 'not-relevant', 'other')),
  note TEXT,
  user_id BIGINT REFERENCES hoggy.users(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'open' CONSTRAINT listing_reports_status CHECK (status IN ('open', 'resolved', 'dismissed')),
  created BIGINT NOT NULL, decided BIGINT, decided_by TEXT);
CREATE INDEX IF NOT EXISTS listing_reports_status_created ON hoggy.listing_reports(status, created);

ALTER TABLE hoggy.submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE hoggy.listing_reports ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON hoggy.submissions, hoggy.listing_reports FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA hoggy FROM PUBLIC;
DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON hoggy.submissions, hoggy.listing_reports FROM %I', r);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA hoggy FROM %I', r);
    END IF;
  END LOOP;
END $$;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'postgres') THEN
    GRANT ALL ON hoggy.submissions, hoggy.listing_reports TO postgres;
    GRANT ALL ON ALL SEQUENCES IN SCHEMA hoggy TO postgres;
  END IF;
END $$;
